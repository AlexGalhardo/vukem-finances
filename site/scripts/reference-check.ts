import fs from "node:fs";
import path from "node:path";
import { pageFile } from "../lib/reference.ts";
import { generatedDir } from "../lib/reference-config.ts";
import { generateAll } from "./generate-reference.ts";

// Regenerates every page in memory and compares it with content/generated: a stale, missing or extra file fails.
function walk(dir: string): string[] {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const full = path.join(dir, e.name);
    return e.isDirectory() ? walk(full) : [full];
  });
}

const expected = new Map(generateAll().map((p) => [path.join(generatedDir, `${p.slug}.md`), pageFile(p)]));
const problems: string[] = [];
for (const [file, content] of expected) {
  const rel = path.relative(generatedDir, file);
  if (!fs.existsSync(file)) problems.push(`${rel}: missing`);
  else if (fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n") !== content) problems.push(`${rel}: stale`);
}
for (const file of walk(generatedDir)) {
  if (!expected.has(file)) problems.push(`${path.relative(generatedDir, file)}: not generated by any source`);
}
if (problems.length > 0) {
  console.error(
    `reference:check failed (run "bun run reference" and commit):\n${problems.map((p) => `  ${p}`).join("\n")}`,
  );
  process.exit(1);
}
console.log(`reference:check ok (${expected.size} pages)`);
