/**
 * Turns resources/css/tokens.css into the TypeScript the mobile app imports
 * (mobile/src/theme/tokens.ts), so web and mobile share one palette. Pure: the
 * CLI is export-tokens.ts and the mobile test calls this to prove the file is fresh.
 */

const BASE_PX = 16;

function block(css: string, selector: string): string {
  const start = css.indexOf(`${selector} {`);
  if (start < 0) throw new Error(`tokens.css has no ${selector} block`);
  const end = css.indexOf("}", start);
  return css.slice(start, end);
}

function declarations(body: string): [string, string][] {
  const out: [string, string][] = [];
  for (const m of body.matchAll(/--vf-([a-z0-9-]+):\s*([^;]+);/g)) out.push([m[1] as string, (m[2] as string).trim()]);
  return out;
}

function camel(name: string): string {
  return name.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());
}

function px(value: string): number {
  const rem = /^([\d.]+)rem$/.exec(value);
  if (rem === null) throw new Error(`not a rem value: ${value}`);
  return Math.round(Number(rem[1]) * BASE_PX);
}

function ms(value: string): number {
  const m = /^(\d+)ms$/.exec(value);
  if (m === null) throw new Error(`not a ms value: ${value}`);
  return Number(m[1]);
}

function object(entries: [string, string | number][], indent: string): string {
  const lines = entries.map(([k, v]) => `${indent}\t${/^\d/.test(k) ? `"${k}"` : k}: ${typeof v === "number" ? v : `"${v}"`},`);
  return `{\n${lines.join("\n")}\n${indent}}`;
}

export function buildTokens(css: string): string {
  const light = declarations(block(css, ":root"));
  const dark = declarations(block(css, ".dark"));

  const colorsOf = (list: [string, string][]): [string, string][] =>
    list.filter(([, v]) => v.startsWith("#")).map(([k, v]): [string, string] => [camel(k), v]);
  const withPrefix = (prefix: string): [string, string][] =>
    light.filter(([k]) => k.startsWith(prefix)).map(([k, v]): [string, string] => [k.slice(prefix.length), v]);

  const spacing = withPrefix("space-").map(([k, v]): [string, number] => [k, px(v)]);
  const fontSize = withPrefix("text-")
    .filter(([k]) => ["xs", "sm", "base", "lg", "xl"].includes(k))
    .map(([k, v]): [string, number] => [k, px(v)]);
  const duration = withPrefix("duration-").map(([k, v]): [string, number] => [k, ms(v)]);
  const get = (name: string): string => {
    const found = light.find(([k]) => k === name);
    if (found === undefined) throw new Error(`tokens.css has no --vf-${name}`);
    return found[1];
  };

  return [
    "// Generated by scripts/export-tokens.ts from resources/css/tokens.css. Do not edit: run",
    "// `bun run scripts/export-tokens.ts` after changing the CSS tokens.",
    "",
    `export const colors = {`,
    `\tlight: ${object(colorsOf(light), "\t")},`,
    `\tdark: ${object(colorsOf(dark), "\t")},`,
    "} as const;",
    "",
    "/** Density-independent pixels: the rem values of the CSS tokens at 16 px. */",
    `export const spacing = ${object(spacing, "")} as const;`,
    "",
    `export const fontSize = ${object(fontSize, "")} as const;`,
    "",
    `export const radius = ${px(get("radius"))};`,
    "",
    "/** The smallest touch target, in density-independent pixels. */",
    `export const targetMin = ${px(get("target-min"))};`,
    "",
    `export const duration = ${object(duration, "")} as const;`,
    "",
    "export type ColorName = keyof typeof colors.light;",
    "",
  ].join("\n");
}
